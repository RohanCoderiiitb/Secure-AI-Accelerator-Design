//=====================================================================
// tb_qif_array_centre.sv -- sampled QIF capture on the CENTRE PE of the
// 5x5 systolic array.
//
// Compile with -g2012, '.' on the include path (for sca_capture.vh and
// qif_schedule.vh).
//
// WHY THE CENTRE PE
// -----------------
// 25 INT8 weights is 2^200 cases, so the array cannot be enumerated.
// Instead one PE is analysed from random samples: the centre PE (row 2,
// col 2), the PE that takes its activation from a west neighbour AND its
// partial sum from a north neighbour.
//
// SECRET vs PLAINTEXT  (+SECRET=wt | act | psum)
// ---------------------------------------------
//   wt    secret = the centre PE's stationary weight (raw INT8)
//   act   secret = the activation entering the centre PE (raw INT8)
//   psum  secret = the partial sum ENTERING the centre PE from the PE
//                  above it (raw value)
// Everything else -- the other centre-PE inputs, all other weights, all
// other activations -- is fresh random plaintext on every trace.
//
// EXHAUSTIVE SECRET SPACE
//   wt, act : all 256 INT8 values; trace i uses value (i mod 256) - 128.
//   psum    : every value the incoming partial sum can actually take in
//             one tile. It is w[0][2]*a0 + w[1][2]*a1, so it lies in
//             [-32512, 32768], but only 61,406 of those integers are a
//             sum of two INT8 products. The list is generated by
//             scripts/gen_psum_space.py and read from +PSUM_SPACE=;
//             trace i uses entry (i mod K). N = K x QREP.
// Walking the secret in order gives every value the same number of
// traces. The pipeline is flushed with zeros between traces, so nothing
// from one trace carries into the next window.
//
// HOW THE psum SECRET IS SET
//   The two PEs above the centre still compute with random plaintext.
//   The north boundary input psum_flat[2] is driven, for the one cycle in
//   which PE(0,2) computes, with  secret - (w[0][2]*a0 + w[1][2]*a1),
//   so the partial sum arriving at the centre PE is exactly the secret.
//   psum_flat is 0 in every other cycle, so the centre PE sees the same
//   0 -> value -> 0 pattern as in the wt/act runs.
//
// ONE OPERATION PER TRACE
// -----------------------
//   1. load all 25 weights (outside the capture window)
//   2. inject ONE activation vector with input skew (row r enters at
//      cycle r), psum_flat tied to 0 for a tile
//   3. capture QCAP cycles from the first injection; the centre PE does
//      its single MAC inside that window
// Only the centre PE is dumped, so the power proxy L(t) is that PE alone.
// Dumping is continuous (no $dumpoff/$dumpon, per sca_capture.vh); the
// capture windows are cut out afterwards from the metadata sidecar, and
// weight load / flush activity falls outside them (rule R4).
//
// SELF-CHECKS (the simulation stops if any fails)
//   * after loading, the centre PE's wt_out must equal the weight meant
//     for it -- catches a wrong assumption about how weights shift in
//   * the centre PE must see exactly one valid operation per window --
//     catches a capture window that is too short
//   * for act, the activation seen at the centre PE must equal the one
//     injected into row 2
//   * for psum, the partial sum seen at the centre PE must equal the
//     secret
//
// Rule R3 holds: secret values live only in testbench variables,
// never inside the dumped PE scope.
//=====================================================================
`timescale 1ns/1ps

module tb_qif_array_centre;

    localparam N    = 8;
    localparam ACCW = 32;
    localparam ROWS = 5;
    localparam COLS = 5;
    localparam CR   = ROWS / 2;            // centre row
    localparam CC   = COLS / 2;            // centre column
    localparam real CLK_PERIOD = 10.0;     // ns

    `include "sca_capture.vh"
    `include "qif_schedule.vh"

    //-----------------------------------------------------------------
    // Clock and DUT
    //-----------------------------------------------------------------
    reg clk = 1'b0;
    always #(CLK_PERIOD/2.0) clk = ~clk;

    reg                    reset_n;
    reg                    wt_load;
    reg  [COLS*N-1:0]      wt_flat;
    reg  [ROWS-1:0]        valid_act_in;
    reg  [ROWS*N-1:0]      act_flat;
    reg  [COLS*ACCW-1:0]   psum_flat;
    wire [COLS*ACCW-1:0]   psum_out;
    wire [COLS-1:0]        valid_sum_out;
    wire [ROWS*N-1:0]      act_out;
    wire [ROWS-1:0]        valid_act_out;

    (* dont_touch = "yes" *)
    systolic_array #(.N(N), .ACCW(ACCW), .ROWS(ROWS), .COLS(COLS)) dut (
        .clk(clk), .reset_n(reset_n), .wt_load(wt_load), .wt_flat(wt_flat),
        .valid_act_in(valid_act_in), .act_flat(act_flat),
        .psum_flat(psum_flat), .psum_out(psum_out),
        .valid_sum_out(valid_sum_out), .act_out(act_out),
        .valid_act_out(valid_act_out)
    );

    // Probes on the centre PE's ports (testbench side, never dumped).
    wire                   c_valid_in = dut.g_row[CR].g_col[CC].pe_inst.valid_in;
    wire signed [N-1:0]    c_act_in   = dut.g_row[CR].g_col[CC].pe_inst.act_in;
    wire signed [N-1:0]    c_wt_out   = dut.g_row[CR].g_col[CC].pe_inst.wt_out;
    wire signed [ACCW-1:0] c_psum_in  = dut.g_row[CR].g_col[CC].pe_inst.psum_in;

    //-----------------------------------------------------------------
    // Capture the centre PE's inputs at the edge where it operates
    //-----------------------------------------------------------------
    reg                    cap_on = 1'b0;
    integer                seen;
    reg signed [N-1:0]     obs_act;
    reg signed [ACCW-1:0]  obs_psum;

    always @(posedge clk) begin
        if (cap_on && c_valid_in === 1'b1) begin
            seen     = seen + 1;
            obs_act  = c_act_in;
            obs_psum = c_psum_in;
        end
    end

    //-----------------------------------------------------------------
    // Stimulus
    //-----------------------------------------------------------------
    string                 SECRET;
    string                 PSUM_SPACE;
    integer                QN, QCAP, QREP, QK;
    integer                i, k, r, c;
    integer                sid, sval, upstream;
    localparam             PSPACE_MAX = 65536;
    reg signed [ACCW-1:0]  PSPACE [0:PSPACE_MAX-1];
    reg signed [N-1:0]     W [0:ROWS-1][0:COLS-1];
    reg signed [N-1:0]     A [0:ROWS-1];

    initial begin
        qif_get_config("qif_array_centre", 1);
        if (!$value$plusargs("SECRET=%s", SECRET)) SECRET = "wt";
        if (!$value$plusargs("QN=%d",     QN))     QN     = 819200;
        if (!$value$plusargs("QCAP=%d",   QCAP))   QCAP   = 8;
        if (SECRET != "wt" && SECRET != "act" && SECRET != "psum") begin
            $display("[QIF] FATAL: +SECRET must be wt, act or psum (got %0s)", SECRET);
            $finish;
        end
        QK = 256;
        if (SECRET == "psum") begin
            if (!$value$plusargs("PSUM_SPACE=%s", PSUM_SPACE)) begin
                $display("[QIF] FATAL: SECRET=psum needs +PSUM_SPACE=<hex file>");
                $finish;
            end
            if (!$value$plusargs("QREP=%d", QREP)) QREP = 1;
            $readmemh(PSUM_SPACE, PSPACE);
            QK = 0;
            while (QK < PSPACE_MAX && ^PSPACE[QK] !== 1'bx) QK = QK + 1;
            if (QK == 0) begin
                $display("[QIF] FATAL: no values read from %0s", PSUM_SPACE);
                $finish;
            end
            QN = QK * QREP;
            $display("[QIF] psum secret space: %0d values in [%0d, %0d], %0d traces each",
                     QK, PSPACE[0], PSPACE[QK-1], QREP);
        end
        $display("[QIF] centre PE (%0d,%0d)  secret=%0s  N=%0d  capture=%0d cycles",
                 CR, CC, SECRET, QN, QCAP);

        qif_open_meta("systolic_array_5x5_centre_pe", CLK_PERIOD, QCAP, QN);
        $dumpfile({OUTDIR, "/", TAG, ".vcd"});
        $dumpvars(0, dut.g_row[CR].g_col[CC].pe_inst);

        reset_n      = 1'b0;
        wt_load      = 1'b0;
        wt_flat      = '0;
        valid_act_in = '0;
        act_flat     = '0;
        psum_flat    = '0;                 // tied to 0 for a tile
        repeat (3) @(posedge clk);
        @(negedge clk) reset_n = 1'b1;
        repeat (2) @(posedge clk);

        for (i = 0; i < QN; i = i + 1) begin
            qif_progress(i, QN);

            // ---- plaintext: everything random ----------------------
            for (r = 0; r < ROWS; r = r + 1) begin
                A[r] = rand_i8(0);
                for (c = 0; c < COLS; c = c + 1)
                    W[r][c] = rand_i8(0);
            end

            // ---- secret ---------------------------------------------
            sid = i % QK;
            if (SECRET == "psum") begin
                sval = PSPACE[sid];
            end else begin
                sval = sid - 128;
                if (SECRET == "wt") W[CR][CC] = sval;
                else                A[CR]     = sval;
            end
            upstream = 0;
            for (r = 0; r < CR; r = r + 1)
                upstream = upstream + W[r][CC] * A[r];

            // ---- load weights: they shift down one row per cycle, so
            //      the bottom row is fed first ----------------------
            for (k = 0; k < ROWS; k = k + 1) begin
                @(negedge clk);
                wt_load = 1'b1;
                for (c = 0; c < COLS; c = c + 1)
                    wt_flat[c*N +: N] = W[ROWS-1-k][c];
            end
            @(negedge clk);
            wt_load = 1'b0;
            wt_flat = '0;
            @(posedge clk);
            #1;
            if (c_wt_out !== W[CR][CC]) begin
                $display("[QIF] FATAL: trace %0d: centre PE holds weight %0d, expected %0d. The weight-loading order in this testbench does not match processing_element.",
                         i, c_wt_out, W[CR][CC]);
                $finish;
            end

            // ---- capture window: one skewed activation vector ------
            seen   = 0;
            cap_on = 1'b1;
            for (k = 0; k < QCAP; k = k + 1) begin
                @(negedge clk);
                valid_act_in = '0;
                act_flat     = '0;
                psum_flat    = '0;
                // PE(0,CC) computes in window cycle CC: inject the offset
                // that makes the centre PE's incoming partial sum = secret
                if (SECRET == "psum" && k == CC)
                    psum_flat[CC*ACCW +: ACCW] = sval - upstream;
                if (k < ROWS) begin
                    valid_act_in[k]   = 1'b1;
                    act_flat[k*N +: N] = A[k];
                end
                @(posedge clk);
                if (k == 0) sca_trace_begin;
            end
            qif_trace_end(sid, sval, -1, -1);
            #1;
            cap_on = 1'b0;

            if (seen != 1) begin
                $display("[QIF] FATAL: trace %0d: centre PE saw %0d valid operations in the window (need exactly 1). Increase +QCAP.", i, seen);
                $finish;
            end
            if (SECRET == "act" && obs_act !== A[CR]) begin
                $display("[QIF] FATAL: trace %0d: centre PE received activation %0d, injected %0d.", i, obs_act, A[CR]);
                $finish;
            end
            if (SECRET == "psum" && obs_psum !== sval) begin
                $display("[QIF] FATAL: trace %0d: centre PE received partial sum %0d, secret is %0d.", i, obs_psum, sval);
                $finish;
            end
            // ---- flush the pipeline with zero inputs (outside window)
            @(negedge clk);
            valid_act_in = '0;
            act_flat     = '0;
            psum_flat    = '0;
            repeat (ROWS + COLS) @(posedge clk);
        end

        $fclose(meta_fd);
        $display("[QIF] done: %0d traces -> %0s/%0s.{vcd,meta.csv}",
                 QN, OUTDIR, TAG);
        $finish;
    end

endmodule
